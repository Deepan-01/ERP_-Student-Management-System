const Result = require("../models/Result");
const PDFDocument = require("pdfkit");
const XLSX = require("xlsx");

const subjectMap = {
  1: ["PIC", "English", "Tamil", "Matrices and calculus", "Physics", "Chemistry"],
  2: ["Computational methods", "English", "Tamil", "BEEE", "Physics", "EG", "PSPP"],
  3: ["DM", "OOPS", "DPCO", "FOE", "FDSA"],
  4: ["PS", "DBMS", "ML", "IBS", "EVS", "OS"],
  5: ["Subject 1", "Subject 2", "Subject 3", "Subject 4", "Subject 5"],
  6: ["Subject 1", "Subject 2", "Subject 3", "Subject 4", "Subject 5", "Subject 6"],
  7: ["Subject 1", "Subject 2", "Subject 3", "Subject 4", "Subject 5"],
  8: ["Subject 1", "Subject 2", "Subject 3", "Subject 4", "Subject 5", "Subject 6"],
};

exports.addResult = async (req, res) => {
  try {
    const { rollNo, name, department, semester: semStr, subject1, subject2, subject3, subject4, subject5, subject6, subject7 } = req.body;
    const semester = Number(semStr);

    const subjects = [subject1, subject2, subject3, subject4, subject5, subject6, subject7]
      .map((s) => Number(s) || 0);

    const count = subjectMap[semester] ? subjectMap[semester].length : 5;
    const validSubjects = subjects.slice(0, count);
    while (validSubjects.length < count) validSubjects.push(0);
    const total = validSubjects.reduce((a, b) => a + b, 0);
    const percentage = count > 0 ? total / count : 0;
    const gpa = Number((percentage / 10).toFixed(2));

    let grade = "";
    if (percentage >= 90) grade = "O";
    else if (percentage >= 80) grade = "A+";
    else if (percentage >= 70) grade = "A";
    else if (percentage >= 60) grade = "B+";
    else if (percentage >= 50) grade = "B";
    else if (percentage >= 40) grade = "C";
    else grade = "RA";

    const resultData = {
      rollNo, name, department, semester,
      subject1: validSubjects[0] || 0,
      subject2: validSubjects[1] || 0,
      subject3: validSubjects[2] || 0,
      subject4: validSubjects[3] || 0,
      subject5: validSubjects[4] || 0,
      total, percentage, gpa, grade,
    };
    if (validSubjects.length > 5) resultData.subject6 = validSubjects[5] || 0;
    if (validSubjects.length > 6) resultData.subject7 = validSubjects[6] || 0;

    const result = await Result.create(resultData);

    res.status(201).json(result);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

exports.getResults = async (req, res) => {
  try {
    const filter = {};
    if (req.user.role === "staff" && req.user.department) {
      filter.department = req.user.department;
    } else if (req.query.department) {
      filter.department = req.query.department;
    }
    const results = await Result.find(filter).sort({ createdAt: -1 });
    res.status(200).json(results);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

exports.deleteResult = async (req, res) => {
  try {
    const result = await Result.findByIdAndDelete(req.params.id);
    if (!result) return res.status(404).json({ message: "Result Not Found" });
    res.status(200).json({ success: true, message: "Result Deleted Successfully" });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

exports.generateMarksheet = async (req, res) => {
  try {
    const result = await Result.findById(req.params.id);
    if (!result) return res.status(404).json({ message: "Result not found" });

    const doc = new PDFDocument();

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader("Content-Disposition", `attachment; filename=${result.rollNo}_marksheet.pdf`);

    doc.pipe(res);

    doc.fontSize(20).text("ERP Student Management System", { align: "center" });
    doc.moveDown();
    doc.fontSize(16).text("Student Marksheet");
    doc.moveDown();
    doc.text(`Roll No : ${result.rollNo}`);
    doc.text(`Name : ${result.name}`);
    doc.text(`Department : ${result.department}`);
    doc.text(`Semester : ${result.semester}`);
    doc.moveDown();

    const subjects = subjectMap[result.semester] || [];
    subjects.forEach((name, i) => {
      const field = `subject${i + 1}`;
      doc.text(`${name} : ${result[field] || 0}`);
    });

    doc.moveDown();
    doc.text(`Total : ${result.total}`);
    doc.text(`Percentage : ${result.percentage}%`);
    doc.text(`Grade : ${result.grade}`);
    doc.text(`GPA : ${result.gpa}`);
    doc.moveDown();
    doc.text("Generated by ERP Student Management System", { align: "center" });

    doc.end();
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

exports.getStudentResults = async (req, res) => {
  try {
    const results = await Result.find({ rollNo: req.user.rollNo }).sort({ semester: 1 });
    res.status(200).json(results);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};

exports.exportResultsExcel = async (req, res) => {
  try {
    const results = await Result.find();
    const data = results.map((r) => {
      const row = {
        RollNo: r.rollNo,
        Name: r.name,
        Department: r.department,
        Semester: r.semester,
      };
      const subjects = subjectMap[r.semester] || [];
      subjects.forEach((name, i) => {
        row[name] = r[`subject${i + 1}`] || 0;
      });
      row.Total = r.total;
      row.Percentage = r.percentage;
      row.Grade = r.grade;
      row.GPA = r.gpa;
      return row;
    });

    const workbook = XLSX.utils.book_new();
    const worksheet = XLSX.utils.json_to_sheet(data);
    XLSX.utils.book_append_sheet(workbook, worksheet, "Results");

    const buffer = XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });

    res.setHeader("Content-Disposition", "attachment; filename=results.xlsx");
    res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
    res.send(buffer);
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
